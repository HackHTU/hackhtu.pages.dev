/** 按学院取专业；未知学院返回 undefined，表示用户可以自由填写。 */
export const getMajorsForCollege = (college: string): string[] | undefined => {
  for (const [name, majors] of Object.entries(MAJORS_BY_COLLEGE)) {
    if (name === college) {
      return majors;
    }
  }

  return undefined;
};

/** 红字字段本身保存完整内容，例如「河南师范大学 美术学院」。 */
export const RED_COLLEGE_PREFIX = "河南师范大学";

export const RED_COLLEGE_OPTIONS = COLLEGES.map(
  (college) => `${RED_COLLEGE_PREFIX} ${college}`
);

/** 兼容旧数据：只有旧值正好是已知学院名时才补上学校前缀。 */
export const normalizeRedCollege = (value: string): string => {
  if (value === "" || value.startsWith(RED_COLLEGE_PREFIX)) {
    return value;
  }

  return COLLEGES.some((college) => college === value)
    ? `${RED_COLLEGE_PREFIX} ${value}`
    : value;
};

export const collegeNameFromRedText = (value: string): string =>
  value.replace(/^河南师范大学\s*/u, "");

